export const provaoTopics:readonly ProvaoTopic[]=[...programTopics,...writingTopics];

export function provaoSubjects(grade:ProvaoGrade|null=null){
 const result:Record<string,string[]>={};
 for(const row of provaoTopics){if(grade&&row.grade!==grade)continue;const topics=result[row.subject]??=[];if(!topics.includes(row.topic))topics.push(row.topic);}
 return result;
}
export function findProvaoTopic(subject:string,topic:string){return provaoTopics.find(row=>row.subject===subject&&row.topic===topic)??null;}
export function isProvaoTopic(subject:string,topic:string,grade:ProvaoGrade|null=null){return provaoTopics.some(row=>row.subject===subject&&row.topic===topic&&(!grade||row.grade===grade));}
